"""Cross-platform `onedir` Desktop App Builder + Windows Inno Setup (`Setup.exe`) & `SHA256SUMS.txt` Packager.

Why `onedir` + `upx=False` (ADR-002):
  - `onefile` unpacks ~100MB into `%TEMP%\\_MEIxxxxx` on every cold launch (8-15s startup delay + AV false positives).
  - `onedir` (`EXE + COLLECT`, `upx=False`) launches in `< 1.5s`, shares DLL pages cleanly, and pairs with
    Inno Setup 6 (`installer/videodownloader.iss`) to produce a crisp `VideoDownloader-Setup-<ver>-x64.exe`!

Outputs in `dist/`:
  - `dist/VideoDownloader/`                             (raw `onedir` bundle, verified via `--smoke-test`)
  - `dist/VideoDownloader-Setup-<ver>-x64.exe`          (Windows non-admin Setup installer when `ISCC.exe` is available)
  - `dist/VideoDownloader-<ver>-Windows-portable.zip`   (portable ZIP with `portable.flag` marker)
  - `dist/SHA256SUMS.txt`                               (cryptographic SHA-256 manifest for self-updater & release)
"""

from __future__ import annotations

import hashlib
import os
from pathlib import Path
import shutil
import subprocess
import sys
import time
import zipfile

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from videodownloader import APP_NAME, __version__  # noqa: E402


def find_iscc_compiler() -> Path | None:
    """Locate Inno Setup 6 `ISCC.exe` across user-scope winget install, Program Files, and PATH."""
    if not sys.platform.startswith("win"):
        return None
    which = shutil.which("ISCC") or shutil.which("ISCC.exe")
    if which:
        return Path(which)
    candidates = [
        Path(os.environ.get("LOCALAPPDATA", "")) / "Programs" / "Inno Setup 6" / "ISCC.exe",
        Path(r"C:\Program Files (x86)\Inno Setup 6\ISCC.exe"),
        Path(r"C:\Program Files\Inno Setup 6\ISCC.exe"),
    ]
    for c in candidates:
        if c.is_file():
            return c
    return None


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fp:
        for chunk in iter(lambda: fp.read(512 * 1024), b""):
            h.update(chunk)
    return h.hexdigest().lower()


RUNTIME_DIRS_EXCLUDED = {"data", "logs", "downloads", "bin", "config"}
RUNTIME_FILES_EXCLUDED_SUFFIXES = (".db", ".db-wal", ".db-shm")


def _is_runtime_artifact(rel_to_bundle: Path) -> bool:
    """True for user data generated by launching the onedir bundle locally (must never ship in releases)."""
    parts = rel_to_bundle.parts
    if parts and parts[0].lower() in RUNTIME_DIRS_EXCLUDED:
        return True
    name = rel_to_bundle.name.lower()
    return name == "portable.flag" or name.endswith(RUNTIME_FILES_EXCLUDED_SUFFIXES) or name.startswith("cookies")


def create_portable_zip(onedir_folder: Path, out_zip: Path) -> None:
    """Package `dist/VideoDownloader/` into a portable `.zip` containing `portable.flag`."""
    if out_zip.exists():
        out_zip.unlink()
    with zipfile.ZipFile(out_zip, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
        for file_path in sorted(onedir_folder.rglob("*")):
            if file_path.is_file() and not _is_runtime_artifact(file_path.relative_to(onedir_folder)):
                rel = file_path.relative_to(onedir_folder.parent)
                zf.write(file_path, arcname=str(rel).replace("\\", "/"))
        zf.writestr(
            f"{onedir_folder.name}/portable.flag",
            "Portable mode marker: keeps data/, logs/, and downloads/ next to VideoDownloader.exe.\n",
        )


def write_sha256sums(dist_dir: Path, artifact_files: list[Path]) -> Path:
    sums_path = dist_dir / "SHA256SUMS.txt"
    lines = []
    for f in artifact_files:
        if f.is_file():
            digest = sha256_file(f)
            lines.append(f"{digest}  {f.name}")
    sums_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return sums_path


def build() -> None:
    assets_dir = ROOT / "videodownloader" / "assets"
    icon_ico = assets_dir / "icon.ico"
    icon_png = assets_dir / "icon.png"
    if not icon_ico.exists() or not icon_png.exists():
        subprocess.run([sys.executable, str(ROOT / "scripts" / "generate_assets.py")], cwd=str(ROOT), check=True)

    dist_dir = ROOT / "dist"
    legacy_onefile = dist_dir / "videodownloader.exe"
    if legacy_onefile.exists():
        try:
            legacy_onefile.unlink()
        except OSError:
            pass

    if sys.platform.startswith("win"):
        try:
            subprocess.run(["taskkill", "/F", "/IM", f"{APP_NAME}.exe"], capture_output=True)
        except Exception:
            pass

    entry = ROOT / "run_desktop.py"
    web_static = ROOT / "videodownloader" / "web_static"
    sep = ";" if sys.platform.startswith("win") else ":"

    cmd = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--noconfirm",
        "--clean",
        "--onedir",
        "--noupx",
        "--name",
        APP_NAME,
        "--add-data",
        f"{assets_dir}{sep}videodownloader/assets",
        "--add-data",
        f"{web_static}{sep}videodownloader/web_static",
        "--collect-data",
        "qfluentwidgets",
        "--collect-data",
        "imageio_ffmpeg",
        "--copy-metadata",
        "imageio_ffmpeg",
        "--collect-all",
        "yt_dlp_ejs",
        "--collect-all",
        "curl_cffi",
        "--hidden-import",
        "PyQt6.QtMultimedia",
        "--hidden-import",
        "PyQt6.QtMultimediaWidgets",
        "--hidden-import",
        "PyQt6.QtNetwork",
        "--hidden-import",
        "pynput.keyboard._win32" if sys.platform.startswith("win") else "pynput.keyboard",
        "--hidden-import",
        "uvicorn.logging",
        "--hidden-import",
        "uvicorn.loops.auto",
        "--hidden-import",
        "uvicorn.protocols.http.auto",
        "--hidden-import",
        "uvicorn.protocols.websockets.auto",
        "--hidden-import",
        "uvicorn.lifespan.on",
    ]

    if sys.platform.startswith("win"):
        cmd += ["--noconsole", "--icon", str(icon_ico)]
    elif sys.platform == "darwin":
        cmd += ["--noconsole", "--icon", str(icon_png)]

    cmd.append(str(entry))

    print(f"[1/4] Building PyInstaller onedir bundle for {APP_NAME} v{__version__}...")
    subprocess.run(cmd, cwd=str(ROOT), check=True)

    warn_file = ROOT / "build" / APP_NAME / f"warn-{APP_NAME}.txt"
    if warn_file.exists():
        warn_lines = [
            ln.strip()
            for ln in warn_file.read_text(encoding="utf-8", errors="replace").splitlines()
            if ln.strip().startswith("invalid module named ")
        ]
        if warn_lines:
            raise RuntimeError(
                f"PyInstaller detected {len(warn_lines)} corrupted modules on disk:\n"
                + "\n".join(warn_lines[:15])
            )

    onedir_out = dist_dir / APP_NAME
    exe_name = f"{APP_NAME}.exe" if sys.platform.startswith("win") else APP_NAME
    out_exe = (
        (dist_dir / f"{APP_NAME}.app" / "Contents" / "MacOS" / APP_NAME)
        if (sys.platform == "darwin" and (dist_dir / f"{APP_NAME}.app").exists())
        else (onedir_out / exe_name)
    )
    if not out_exe.exists():
        raise FileNotFoundError(f"Expected compiled executable not found: {out_exe}")

    report_file = ROOT / "build" / "exe_smoke_report.json"
    if report_file.exists():
        report_file.unlink()
    print(f"[2/4] Verifying compiled binary via --smoke-test: {out_exe}")
    t0 = time.perf_counter()
    subprocess.run([str(out_exe), "--smoke-test", str(report_file)], cwd=str(out_exe.parent), check=True, timeout=60)
    cold_elapsed = time.perf_counter() - t0
    if not report_file.exists():
        raise RuntimeError("Compiled binary exited without writing smoke test report!")
    print(f"[OK] Binary smoke test passed in {cold_elapsed:.2f}s!\n" + report_file.read_text(encoding="utf-8"))

    release_artifacts: list[Path] = []

    if sys.platform.startswith("win"):
        portable_zip = dist_dir / f"{APP_NAME}-{__version__}-Windows-portable.zip"
        print(f"[3/4] Creating portable archive: {portable_zip.name}")
        create_portable_zip(onedir_out, portable_zip)
        release_artifacts.append(portable_zip)

        iscc = find_iscc_compiler()
        iss_script = ROOT / "installer" / "videodownloader.iss"
        if iscc and iss_script.exists():
            print(f"[4/4] Compiling Windows Setup.exe with Inno Setup ({iscc})...")
            subprocess.run(
                [str(iscc), f"/DMyAppVersion={__version__}", str(iss_script)],
                cwd=str(iss_script.parent),
                check=True,
            )
            setup_exe = dist_dir / f"{APP_NAME}-Setup-{__version__}-x64.exe"
            if setup_exe.exists():
                sz_mb = setup_exe.stat().st_size / (1024 * 1024)
                print(f"[OK] Compiled installer: {setup_exe} ({sz_mb:.1f} MB)")
                release_artifacts.insert(0, setup_exe)
        else:
            print("[WARN] Inno Setup 6 (ISCC.exe) not found; skipped Setup.exe compilation.")

    elif sys.platform.startswith("linux"):
        tar_base = dist_dir / f"{APP_NAME}-{__version__}-Linux-x64"
        archive_path = Path(shutil.make_archive(str(tar_base), "gztar", root_dir=str(dist_dir), base_dir=APP_NAME))
        release_artifacts.append(archive_path)

    if release_artifacts:
        sums = write_sha256sums(dist_dir, release_artifacts)
        print(f"[OK] Generated {sums}:\n" + sums.read_text(encoding="utf-8"))


if __name__ == "__main__":
    build()
